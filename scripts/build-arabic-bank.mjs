// Build src/arabicCategoriesBank.js from the fact-checked category files audit/arabic/<id>.final.json.
// Strips research-only fields (src, itunes*, trackId) and normalizes audio tiles to the song-clip shape
// used by SongClipPlayer ({q, a, artist, previewUrl, clipStart, duration, sourceUrl}).
// Usage: node scripts/build-arabic-bank.mjs
import fs from "node:fs";

// Order = order shown in the "Arabic" group on the category screen (as the owner listed them).
export const ARABIC_CATEGORY_META = [
  ["ar_ghumaida", "الغميضة", "\u{1F9F5}"],
  ["ar_prophets", "قصص الأنبياء", "\u{1F4D6}"],
  // No flag emoji: Windows renders regional-indicator pairs as letters ("IQ"), not flags.
  ["ar_iraqi_songs", "أغاني عراقية", "\u{1F3BB}"],
  ["ar_jewelry", "مجوهرات", "\u{1F48D}"],
  ["ar_songs_2016", "أغاني 2016", "\u{1F3A7}"],
  ["ar_turkish_series", "مسلسلات تركية", "\u{1F4FA}"],
  ["ar_egyptian_songs", "أغاني مصرية", "\u{1F3A4}"],
  ["ar_complete_word", "كمل الكلمة", "✍️"],
  ["ar_uae_restaurants", "مطاعم الإمارات", "\u{1F37D}️"],
  ["ar_cars", "سيارات", "\u{1F697}"],
  ["ar_coop", "الجمعية", "\u{1F6D2}"],
  ["ar_products", "منتجات", "\u{1F4E6}"],
  ["ar_general", "معلومات عامة", "\u{1F4A1}"],
  ["ar_brands", "براندات", "\u{1F45C}"],
];

const AUDIO_PROMPT = "خمّن الأغنية من المقطع";
const clean = (s) => String(s ?? "").replace(/\s+/g, " ").trim();

function toEntry(raw, where) {
  if (!raw || typeof raw !== "object") throw new Error(`${where}: not an object`);
  const a = clean(raw.a);
  if (!a) throw new Error(`${where}: empty answer`);
  if (raw.previewUrl) {
    const previewUrl = clean(raw.previewUrl);
    if (!/^https:\/\/audio-ssl\.itunes\.apple\.com\//.test(previewUrl)) throw new Error(`${where}: unexpected previewUrl host ${previewUrl}`);
    // clipStart comes from scripts/set-arabic-clip-starts.mjs (where the vocals are in the 30 s preview); 0 if unset.
    const clipStart = Number.isFinite(raw.clipStart) ? Math.max(0, Math.min(16, raw.clipStart)) : 0;
    const entry = { q: AUDIO_PROMPT, a, artist: clean(raw.artist), previewUrl, clipStart, duration: 14 };
    if (raw.sourceUrl) entry.sourceUrl = clean(raw.sourceUrl);
    return entry;
  }
  const q = clean(raw.q);
  if (!q) throw new Error(`${where}: empty question`);
  return { q, a };
}

const bank = {};
const missing = [];
for (const [id, label, icon] of ARABIC_CATEGORY_META) {
  const file = `audit/arabic/${id}.final.json`;
  if (!fs.existsSync(file)) { missing.push(id); continue; }
  const data = JSON.parse(fs.readFileSync(file, "utf8"));
  const cat = { label, icon, color: "#22D3EE", isArabic: true };
  for (const tier of [200, 400, 600]) {
    const list = Array.isArray(data[tier]) ? data[tier] : Array.isArray(data[String(tier)]) ? data[String(tier)] : [];
    cat[tier] = list.map((e, i) => toEntry(e, `${id} ${tier} #${i}`));
  }
  bank[id] = cat;
}

const ids = Object.keys(bank);
const body = ids.map((id) => {
  const c = bank[id];
  const tiers = [200, 400, 600].map((t) => `    ${t}: [\n${c[t].map((e) => `      ${JSON.stringify(e)},`).join("\n")}\n    ],`).join("\n");
  return `  ${id}: {\n    label: ${JSON.stringify(c.label)},\n    icon: ${JSON.stringify(c.icon)},\n    color: ${JSON.stringify(c.color)},\n    isArabic: true,\n${tiers}\n  },`;
}).join("\n");

const out = `// Arabic categories (SeenJeem-style), grouped under "Arabic" on the category screen.
// AUTO-GENERATED by scripts/build-arabic-bank.mjs from audit/arabic/<id>.final.json — edit those, then rebuild.
// Entries with previewUrl are 30-second iTunes song previews and play on the song-clip screen.
const ARABIC_CATEGORIES_BANK = {
${body}
};

export const ARABIC_CATEGORY_IDS = ${JSON.stringify(ids)};
export default ARABIC_CATEGORIES_BANK;
`;
fs.writeFileSync("src/arabicCategoriesBank.js", out);
for (const id of ids) {
  const c = bank[id];
  const audio = [200, 400, 600].map((t) => c[t].filter((e) => e.previewUrl).length);
  console.log(id.padEnd(20), [200, 400, 600].map((t) => String(c[t].length).padStart(4)).join(""), audio.some(Boolean) ? `  audio ${audio.join("/")}` : "");
}
if (missing.length) console.log("missing final files:", missing.join(", "));
